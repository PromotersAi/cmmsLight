<?php
/**
 * CMMS i18n - trilingual interface (Hebrew, English, Arabic).
 *
 * We don't use WP's .mo/.po loading because we want the user to be able to
 * switch language live with a click, independent of the WP site language.
 * Selection is stored in cookie ('cmms_lang') and overridable via ?cmms_lang=xx.
 */
if ( ! defined( 'ABSPATH' ) ) exit;

class CMMS_I18n {

    const COOKIE = 'cmms_lang';
    const DEFAULT_LANG = 'he';

    private static $current = null;

    public static function langs() {
        return array(
            'he' => array( 'name' => 'עברית',  'dir' => 'rtl', 'code' => 'he' ),
            'en' => array( 'name' => 'English', 'dir' => 'ltr', 'code' => 'en' ),
            'ar' => array( 'name' => 'العربية', 'dir' => 'rtl', 'code' => 'ar' ),
        );
    }

    public static function current() {
        if ( self::$current !== null ) return self::$current;
        if ( isset( $_GET['cmms_lang'] ) ) {
            $cand = sanitize_key( wp_unslash( $_GET['cmms_lang'] ) );
            if ( isset( self::langs()[ $cand ] ) ) {
                self::set_cookie( $cand );
                // Also persist to WP user_meta so background dispatch (cron)
                // can later look up THIS user's preferred language.
                if ( is_user_logged_in() ) {
                    update_user_meta( get_current_user_id(), 'cmms_language', $cand );
                }
                self::$current = $cand;
                return $cand;
            }
        }
        if ( isset( $_COOKIE[ self::COOKIE ] ) ) {
            $cand = sanitize_key( wp_unslash( $_COOKIE[ self::COOKIE ] ) );
            if ( isset( self::langs()[ $cand ] ) ) {
                self::$current = $cand;
                return $cand;
            }
        }
        // If logged in and they previously picked a language, prefer that.
        if ( is_user_logged_in() ) {
            $stored = get_user_meta( get_current_user_id(), 'cmms_language', true );
            if ( $stored && isset( self::langs()[ $stored ] ) ) {
                self::$current = $stored;
                return $stored;
            }
        }
        self::$current = self::DEFAULT_LANG;
        return self::$current;
    }

    public static function set_cookie( $lang ) {
        if ( ! headers_sent() ) {
            setcookie( self::COOKIE, $lang, time() + 60 * 60 * 24 * 365, COOKIEPATH ?: '/', COOKIE_DOMAIN, is_ssl(), true );
            $_COOKIE[ self::COOKIE ] = $lang;
        }
    }

    public static function dir() {
        $langs = self::langs();
        return $langs[ self::current() ]['dir'];
    }

    public static function t( $key ) {
        $strings = self::strings();
        $lang = self::current();
        if ( isset( $strings[ $lang ][ $key ] ) ) return $strings[ $lang ][ $key ];
        if ( isset( $strings['en'][ $key ] ) ) return $strings['en'][ $key ];
        return ''; // empty rather than the raw key, so missing keys aren't ugly
    }

    /**
     * Translate a key in a SPECIFIC language (not the current request language).
     * Used by background cron / notification dispatch where we render messages
     * in the recipient user's preferred language, not the actor's.
     */
    public static function t_in( $key, $lang ) {
        $strings = self::strings();
        if ( ! $lang || ! isset( $strings[ $lang ] ) ) $lang = self::default_lang();
        if ( isset( $strings[ $lang ][ $key ] ) ) return $strings[ $lang ][ $key ];
        if ( isset( $strings['en'][ $key ] ) ) return $strings['en'][ $key ];
        return '';
    }

    public static function default_lang() {
        return defined( 'self::DEFAULT_LANG' ) ? self::DEFAULT_LANG : 'he';
    }

    public static function e( $key ) {
        echo esc_html( self::t( $key ) );
    }

